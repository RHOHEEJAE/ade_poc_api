-- ------------------------------------------------------------
-- 공개 API 역할은 이 스키마에 접근하지 못하게 한다
-- ------------------------------------------------------------
REVOKE ALL ON SCHEMA ade FROM anon, authenticated;

-- ------------------------------------------------------------
-- 수집 API 계정: 넣기 · 읽기 · 채번만. 고치기 · 지우기 권한이 없다
-- 비밀번호 자리를 바꿔 실행한다. 비밀번호는 이 파일에 남기지 않는다.
-- 연결 풀러로 접속할 때 사용자 이름은 'ade_collector.<프로젝트 ref>' 형식이다.
-- ------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ade_collector') THEN
    CREATE ROLE ade_collector LOGIN;
  END IF;
END $$;
ALTER ROLE ade_collector WITH LOGIN PASSWORD '<여기에-비밀번호>';
GRANT USAGE ON SCHEMA ade TO ade_collector;
GRANT INSERT, SELECT ON ade.collection_request_history, ade.event_history, ade.diagnosis_history
  TO ade_collector;
GRANT USAGE ON SEQUENCE ade.seq_collection_request_id, ade.seq_event_id, ade.seq_diagnosis_id
  TO ade_collector;
