COMMENT ON COLUMN ade.event_history.event_properties IS '이벤트 원형 (event · properties 전체)';
COMMENT ON COLUMN ade.event_history.created_ts IS '생성된 시각';
COMMENT ON COLUMN ade.event_history.updated_ts IS '마지막으로 수정된 시각';
COMMENT ON COLUMN ade.event_history.created_by IS '생성한 주체';
COMMENT ON COLUMN ade.event_history.updated_by IS '마지막으로 수정한 주체';

