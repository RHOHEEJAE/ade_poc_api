-- 원시 DB 스키마 (PoC, Supabase Postgres). 사내 DB 네이밍 컨벤션(hecto-db-naming) 기준
-- Supabase 대시보드 → SQL Editor 에서 실행한다. 여러 번 실행해도 된다.
--
-- 엔드포인트별 적재
--   POST /track             collection_request_history 1행 + event_history N행
--   POST /engage · /groups  collection_request_history 1행
--   POST /diag              diagnosis_history 1행
--
-- 테이블은 public 이 아니라 ade 스키마에 둔다. Supabase 는 public 을 REST API 로 내보내므로,
-- ade 는 Settings → API → Exposed schemas 에 넣지 않는다.
--
-- 규약 예외 한 곳: event_history.analytics_user_no 는 번호(varchar(40)) 대신 varchar(200).
-- SDK distinct_id 가 '$device:' + UUID 로 44자라 기본 크기에 들어가지 않는다(04. 타입 「분류어가 정한다」).

CREATE SCHEMA IF NOT EXISTS ade;

CREATE TABLE IF NOT EXISTS ade.collection_request_history (
    collection_request_id    bigint          NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME ade.seq_collection_request_id),
    received_ts              timestamptz     NOT NULL,
    server_name              varchar(200)    NOT NULL,
    endpoint_type_code       varchar(20)     NOT NULL,
    client_ip                varchar(45),
    origin_url               varchar(2000),
    referrer_url             varchar(2000),
    user_agent_content       text,
    content_type_name        varchar(200),
    query_string_content     text,
    request_body_content     text            NOT NULL,
    body_byte_num            integer         NOT NULL,
    event_count              integer         NOT NULL DEFAULT 0,
    parse_error_type_code    varchar(20),
    created_ts               timestamptz     NOT NULL DEFAULT now(),
    updated_ts               timestamptz     NOT NULL,
    created_by               varchar(50)     NOT NULL,
    updated_by               varchar(50)     NOT NULL,
    CONSTRAINT pk_collection_request_history PRIMARY KEY (collection_request_id),
    CONSTRAINT ck_collection_request_history_endpoint_allowed
        CHECK (endpoint_type_code IN ('track', 'engage', 'groups'))
);

CREATE INDEX IF NOT EXISTS ix_collection_request_history_received_ts
    ON ade.collection_request_history (received_ts);

COMMENT ON TABLE ade.collection_request_history IS '수집 요청 원본 이력. 요청 하나가 한 행';
COMMENT ON COLUMN ade.collection_request_history.collection_request_id IS '수집 요청 식별자';
COMMENT ON COLUMN ade.collection_request_history.received_ts IS '수집 서버가 요청을 받은 시각';
COMMENT ON COLUMN ade.collection_request_history.server_name IS '요청을 받은 서버 인스턴스';
COMMENT ON COLUMN ade.collection_request_history.endpoint_type_code IS '수집 경로 (track · engage · groups)';
COMMENT ON COLUMN ade.collection_request_history.client_ip IS '요청한 사용자 IP';
COMMENT ON COLUMN ade.collection_request_history.origin_url IS 'Origin 헤더 값';
COMMENT ON COLUMN ade.collection_request_history.referrer_url IS 'Referer 헤더 값';
COMMENT ON COLUMN ade.collection_request_history.user_agent_content IS 'User-Agent 헤더 값';
COMMENT ON COLUMN ade.collection_request_history.content_type_name IS 'Content-Type 헤더 값 (charset 포함)';
COMMENT ON COLUMN ade.collection_request_history.query_string_content IS '쿼리 문자열 원문';
COMMENT ON COLUMN ade.collection_request_history.request_body_content IS '요청 본문 바이트의 base64';
COMMENT ON COLUMN ade.collection_request_history.body_byte_num IS '요청 본문 크기 (base64 전, 바이트)';
COMMENT ON COLUMN ade.collection_request_history.event_count IS '이 요청에서 이벤트 이력으로 넣은 건수';
COMMENT ON COLUMN ade.collection_request_history.parse_error_type_code IS '본문을 이벤트로 풀지 못한 사유';
COMMENT ON COLUMN ade.collection_request_history.created_ts IS '생성된 시각';
COMMENT ON COLUMN ade.collection_request_history.updated_ts IS '마지막으로 수정된 시각';
COMMENT ON COLUMN ade.collection_request_history.created_by IS '생성한 주체';
COMMENT ON COLUMN ade.collection_request_history.updated_by IS '마지막으로 수정한 주체';

CREATE TABLE IF NOT EXISTS ade.event_history (
    event_id                 bigint          NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME ade.seq_event_id),
    collection_request_id    bigint          NOT NULL,
    received_ts              timestamptz     NOT NULL,
    batch_seq                integer         NOT NULL,
    event_name               varchar(200),
    source_event_no          varchar(40),
    analytics_user_no        varchar(200),
    occurred_ts              timestamptz,
    application_no           varchar(40),
    build_no                 varchar(40),
    record_type_code         varchar(20),
    collection_grade_code    varchar(20),
    collection_source_code   varchar(20),
    verdict_code             varchar(20),
    role_code                varchar(20),
    service_code             varchar(20),
    event_properties         json            NOT NULL,
    created_ts               timestamptz     NOT NULL DEFAULT now(),
    updated_ts               timestamptz     NOT NULL,
    created_by               varchar(50)     NOT NULL,
    updated_by               varchar(50)     NOT NULL,
    CONSTRAINT pk_event_history PRIMARY KEY (event_id),
    CONSTRAINT ux_event_history_collection_request_id_batch_seq
        UNIQUE (collection_request_id, batch_seq)
);

CREATE INDEX IF NOT EXISTS ix_event_history_received_ts ON ade.event_history (received_ts);
CREATE INDEX IF NOT EXISTS ix_event_history_source_event_no ON ade.event_history (source_event_no);

COMMENT ON TABLE ade.event_history IS '원시 이벤트 이력. track 요청을 풀어 이벤트 하나가 한 행';
COMMENT ON COLUMN ade.event_history.event_id IS '이벤트 식별자';
COMMENT ON COLUMN ade.event_history.collection_request_id IS '이 이벤트가 나온 수집 요청 식별자';
COMMENT ON COLUMN ade.event_history.received_ts IS '수집 서버가 요청을 받은 시각';
COMMENT ON COLUMN ade.event_history.batch_seq IS '요청 배치 안에서의 순번 (0부터)';
COMMENT ON COLUMN ade.event_history.event_name IS '이벤트 이름 (예: $ade_click)';
COMMENT ON COLUMN ade.event_history.source_event_no IS 'SDK가 부여한 이벤트 키 ($insert_id)';
COMMENT ON COLUMN ade.event_history.analytics_user_no IS 'SDK 사용자 구분값 (distinct_id)';
COMMENT ON COLUMN ade.event_history.occurred_ts IS '이벤트가 일어난 시각 (브라우저 시계)';
COMMENT ON COLUMN ade.event_history.application_no IS '발생 앱 식별값 (application_id)';
COMMENT ON COLUMN ade.event_history.build_no IS '발생 빌드 식별값 (build_id)';
COMMENT ON COLUMN ade.event_history.record_type_code IS '기록 유형 (behavior · system · context)';
COMMENT ON COLUMN ade.event_history.collection_grade_code IS '수집 등급 (guaranteed · observed)';
COMMENT ON COLUMN ade.event_history.collection_source_code IS '수집 경로 (codegen · direct · auto)';
COMMENT ON COLUMN ade.event_history.verdict_code IS '코드젠 판정';
COMMENT ON COLUMN ade.event_history.role_code IS '이벤트 요소 자기 선언의 role';
